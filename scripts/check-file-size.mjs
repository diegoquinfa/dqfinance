#!/usr/bin/env node
/**
 * Pre-commit check: no authored file may exceed TOKEN_LIMIT tokens (1 token = 4 bytes).
 *
 * - Only staged files are checked, and the *staged blob* is measured, not the working tree,
 *   so a partially staged file is judged on what will actually be committed.
 * - Lockfiles, codegen output, the i18n catalogs, build output and binaries are ignored: no agent authors them.
 *
 * Wired up by .githooks/pre-commit (see scripts/install-hooks.mjs).
 */
import { execFileSync } from 'node:child_process'
import { pathToFileURL } from 'node:url'

export const TOKEN_LIMIT = 5_000
export const BYTES_PER_TOKEN = 4
export const BYTE_LIMIT = TOKEN_LIMIT * BYTES_PER_TOKEN

export const tokens = (bytes) => bytes / BYTES_PER_TOKEN

/** Paths no agent authors. Rules: `*.ext` matches the basename suffix, `dir/` any folder, `dir/*.ext` that folder's files, otherwise the basename. */
const IGNORED = [
  // Lockfiles
  'pnpm-lock.yaml',
  'package-lock.json',
  'yarn.lock',
  'bun.lockb',
  '*.lock',
  'skills-lock.json',
  // Installed artifacts, refreshed by their tooling (skills-lock.json tracks them)
  '.agents/skills/',
  // Generated by tools; AGENTS.md lists them under "Generated files are not edited by hand"
  '*.gen.ts', // routeTree.gen.ts and friends
  'auth.schema.ts', // `pnpm --filter @dqfinance/api auth:schema`
  'worker-configuration.d.ts', // wrangler types
  'migrations/', // drizzle-kit SQL
  '*_snapshot.json', // drizzle-kit meta snapshots
  'paraglide/', // paraglide output
  'project.inlang/', // inlang project cache
  // Paraglide keeps one catalog per locale; every feature grows them, and they are not files to split
  'packages/i18n/messages/*.json',
  // Build output, in case it ever gets staged
  'dist/',
  'build/',
  'coverage/',
  '.wrangler/',
  '.turbo/',
  // Binaries and media: a byte count says nothing useful about them
  '*.png',
  '*.jpg',
  '*.jpeg',
  '*.gif',
  '*.webp',
  '*.avif',
  '*.ico',
  '*.bmp',
  '*.tiff',
  '*.pdf',
  '*.zip',
  '*.gz',
  '*.tar',
  '*.exe',
  '*.dll',
  '*.so',
  '*.dylib',
  '*.wasm',
  '*.woff',
  '*.woff2',
  '*.ttf',
  '*.otf',
  '*.eot',
  '*.mp3',
  '*.mp4',
  '*.mov',
  '*.webm',
  '*.db',
  '*.sqlite',
]

export function isIgnored(file) {
  const path = file.replaceAll('\\', '/').toLowerCase()
  const base = path.slice(path.lastIndexOf('/') + 1)
  return IGNORED.some((rule) => {
    if (rule.startsWith('*.')) return base.endsWith(rule.slice(1))
    if (rule.endsWith('/')) return path.includes(`/${rule}`) || path.startsWith(rule)
    if (rule.includes('/*.')) {
      const dir = rule.slice(0, rule.indexOf('/*'))
      return path.startsWith(`${dir}/`) && base.endsWith(rule.slice(rule.indexOf('*') + 1))
    }
    return base === rule
  })
}

const group = (value) => new Intl.NumberFormat('en-US').format(value)

/** The failure message, including how to split a file in this repository. */
export function buildReport(over) {
  const many = over.length > 1
  return [
    `ERROR: ${over.length} staged file${many ? 's' : ''} exceed${many ? '' : 's'} ${group(TOKEN_LIMIT)} tokens (${group(BYTE_LIMIT)} bytes, 1 token = ${BYTES_PER_TOKEN} bytes):`,
    '',
    ...over.flatMap(({ file, bytes }) => [
      `  ${file}`,
      `    ${group(Math.round(tokens(bytes)))} tokens, ${group(bytes)} bytes, ${group(bytes - BYTE_LIMIT)} over the limit`,
    ]),
    '',
    'Split before committing. Split at a concept seam, never mid-function and never by line count:',
    '',
    '  1. One file, one job. A feature folder holds one file per use case:',
    '     create-thing.ts, list-things.ts, thing.schema.ts, thing.routes.ts, thing.tools.ts',
    '  2. Move grouped code out:',
    '     types and zod schemas  -> <entity>.schema.ts or types.ts',
    '     constants and literals -> constants.ts, or a .json data file',
    '     tests and fixtures     -> <name>.test.ts, <name>.fixtures.ts',
    '  3. Extract the pure logic (calculations, parsing, rules) into its own module and leave',
    '     the caller thin: it calls, it does not compute.',
    '  4. Name every new file after what it contains, then re-stage what you moved: git add <paths>',
    '',
    'Exempt: lockfiles, codegen, the i18n catalogs and binaries (listed in scripts/check-file-size.mjs).',
    'Justified one-off? Bypass once with: git commit --no-verify',
  ].join('\n')
}

function stagedFiles(root) {
  const out = execFileSync('git', ['diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z'], {
    cwd: root,
    encoding: 'utf8',
  })
  return out.split('\0').filter(Boolean)
}

function stagedSize(root, file) {
  const size = execFileSync('git', ['cat-file', '-s', `:${file}`], { cwd: root, encoding: 'utf8' })
  return Number(size.trim())
}

/** Staged, authored files above the limit, with their staged byte size. */
export function checkStagedFiles(root) {
  return stagedFiles(root)
    .filter((file) => !isIgnored(file))
    .map((file) => ({ file, bytes: stagedSize(root, file) }))
    .filter(({ bytes }) => bytes > BYTE_LIMIT)
}

function main() {
  const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim()
  const over = checkStagedFiles(root)
  if (over.length === 0) return
  console.error(buildReport(over))
  process.exit(1)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
